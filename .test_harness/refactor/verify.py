"""Prove a wave moved text without changing any of it.

The original .pyw is read out of git at the pinned BASELINE commit, not from HEAD, so this
proof keeps meaning the same thing after the first wave is committed. The new text is the
shrunk .pyw plus every file under yt_msd/. Both are reduced to meaningful lines and compared
as multisets, so a moved function that was retyped, truncated or dropped shows up as a
difference instead of being trusted. The only lines allowed to be new are the ones this tool
generates itself, plus the content edits recorded in approved_edits.txt.
"""
import collections
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import splitlib  # noqa: E402

APPROVALS = os.path.join(HERE, "approved_edits.txt")

# The pre-split entry point this proof compares against. Pinned to a commit rather than left
# as HEAD on purpose: HEAD is the split's starting point only until the first wave is
# committed, after which HEAD is already a moved file and the comparison would silently start
# proving the split against itself. 4958cdc is yt-msd-gui.pyw at 13,758 lines, one file, before
# wave 1. Change it only by choosing a new starting point deliberately.
BASELINE = "4958cdc"

GEN_PREFIXES = (
    "# Open Source Software under the Apache License, Version 2.0",
    "# Part of the yt-msd GUI package",
    "# Extracted from yt-msd-gui.pyw during the 3.5 modularisation",
    "# moved out of this file during the 3.5 modularisation",
    "# re-exported here so the entry point",
    "# split proceeds. The final wave replaces",
    "# Temporary during the split",
    "# to be reachable for",
    "# Suite runs a copy of this file",
    "# Subpackage of the yt-msd GUI package",
    '"""The yt-msd GUI package, split out of the single',
    "_SRC_DIR = os.path.dirname",
    "if _SRC_DIR not in sys.path",
    "sys.path.insert(0, _SRC_DIR)",
)

def load_approvals():
    """The content edits a human has reviewed and signed off, one per wave.

    verify.py's default promise is "nothing was changed". Waves that deliberately rewrite a
    line - the wave-2 settings seam - have to say so, and saying so belongs in a reviewable
    file rather than in a loosened check. `python verify.py --record` writes the exact lines a
    wave removed and added into APPROVALS; a normal run then requires the residual difference
    to match that file in both directions, so an approval that is no longer used is as much of
    a failure as an unapproved edit.
    """
    approved_lost = collections.Counter()
    approved_new = collections.Counter()
    if not os.path.exists(APPROVALS):
        return approved_lost, approved_new
    with open(APPROVALS, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            tag, _, text = line.partition("\t")
            if tag == "LOST":
                approved_lost[text] += 1
            elif tag == "NEW":
                approved_new[text] += 1
    return approved_lost, approved_new


def record_approvals(lost, new):
    with open(APPROVALS, "w", encoding="utf-8") as fh:
        fh.write("# Declared content edits, generated by `python verify.py --record`.\n")
        fh.write("# LOST = a line the original had and the corpus no longer has.\n")
        fh.write("# NEW  = a line the corpus has that the original did not, and that is not a\n")
        fh.write("#        plain import or re-export the splitter writes by itself.\n")
        fh.write("# Review this file before accepting it: every line here is a promise that a\n")
        fh.write("# behaviour change was intended.\n")
        for text, n in sorted(lost.items()):
            for _ in range(n):
                fh.write("LOST\t%s\n" % text)
        for text, n in sorted(new.items()):
            for _ in range(n):
                fh.write("NEW\t%s\n" % text)
    return len(lost), len(new)


def meaningful(text):
    out = []
    for raw in text.splitlines():
        s = raw.strip()
        if not s:
            continue
        if s.startswith(GEN_PREFIXES):
            continue
        out.append(s)
    return out


def new_corpus():
    parts = [splitlib.read_pyw()]
    for root, _dirs, files in os.walk(splitlib.PKG_DIR):
        for name in sorted(files):
            if name.endswith(".py"):
                with open(os.path.join(root, name), "r", encoding="utf-8") as fh:
                    parts.append(fh.read())
    return "\n".join(parts)


def structural_check():
    """Every definition must exist exactly once across the whole corpus.

    A splice bug once duplicated the file header and its import block; the line-multiset
    comparison missed it because import lines are whitelisted as generated text. Counting
    definitions closes that hole: a definition that appears twice, or appears in two
    modules, is a move that went wrong.
    """
    import ast as _ast
    defs = collections.Counter()
    files = [splitlib.PYW]
    for root, _dirs, found in os.walk(splitlib.PKG_DIR):
        for name in sorted(found):
            if name.endswith(".py"):
                files.append(os.path.join(root, name))
    for path in files:
        with open(path, "r", encoding="utf-8") as fh:
            src = fh.read()
        try:
            tree = _ast.parse(src)
        except SyntaxError as exc:
            print("SYNTAX ERROR in %s: %s" % (path, exc))
            return 1
        for node in tree.body:
            if isinstance(node, (_ast.FunctionDef, _ast.ClassDef)):
                defs[node.name] += 1
    dupes = {n: c for n, c in defs.items() if c > 1}
    if dupes:
        print("DUPLICATED DEFINITIONS (%d)" % len(dupes))
        for name, count in sorted(dupes.items()):
            print("  %-34s defined %d times" % (name, count))
        return 1
    print("definitions across the corpus : %d, each exactly once" % len(defs))
    return 0


def main():
    record = "--record" in sys.argv
    original = subprocess.run(
        ["git", "-C", splitlib.ROOT, "show", "%s:GUI Source Code/yt-msd-gui.pyw" % BASELINE],
        capture_output=True, text=True, encoding="utf-8").stdout
    if not original:
        print("could not read HEAD's copy of the .pyw")
        return 1

    before = collections.Counter(meaningful(original))
    after = collections.Counter(meaningful(new_corpus()))

    lost = before - after
    extra = after - before
    # Reviewed exceptions: content changes the wave extractor did not make, approved by hand
    # and recorded here so verify.py stays a hard gate instead of being quietly loosened. The
    # entry point header claimed the program was one file; after wave 1 it no longer was, so
    # the claim was corrected. Comments only, nothing behavioural.
    for approved in ("# Yeah it's all one file, what are you going to do about it?",
                     "# Modular file systems are for sane people"):
        if approved in lost:
            lost.pop(approved)
    print("original meaningful lines : %d" % sum(before.values()))
    print("after   meaningful lines  : %d" % sum(after.values()))
    print("lines missing            : %d" % sum(lost.values()))
    print("lines new                : %d" % sum(extra.values()))
    for line, n in sorted(lost.items()):
        print("  LOST  x%d  %s" % (n, line[:110]))
    # Everything new must be an import, a re-export body line this tool wrote, or a comment.
    moved = set()
    for _wave, groups in splitlib.wave_plan().items():
        for _dotted, names in groups:
            moved.update(names)
    suspect = collections.Counter(l for l in extra
               if not (l.startswith(("import ", "from ")) or l.startswith("#")
                       or l.startswith("_SRC_DIR") or l.startswith("sys.path")
                       or l.startswith("if hasattr(_") or l.startswith("_") and " = _" in l
                       or l == ")" or (l.endswith(",") and l[:-1] in moved)))

    approved_lost, approved_new = load_approvals()
    unapproved_lost = lost - approved_lost
    stale_lost = approved_lost - lost
    unapproved_new = suspect - approved_new
    stale_new = approved_new - suspect

    if record:
        n_lost, n_new = record_approvals(lost, suspect)
        print("\nrecorded %d removed and %d added lines as declared edits -> %s"
              % (n_lost, n_new, APPROVALS))
        return structural_check()

    if unapproved_lost or unapproved_new:
        print("UNAPPROVED content edits (%d removed, %d added) - review and re-record"
              % (sum(unapproved_lost.values()), sum(unapproved_new.values())))
        for line, n in sorted(unapproved_lost.items()):
            print("  LOST  x%d  %s" % (n, line[:110]))
        for line, n in sorted(unapproved_new.items()):
            print("  NEW   x%d  %s" % (n, line[:110]))
        return 1

    if stale_lost or stale_new:
        print("DECLARED EDITS NO LONGER PRESENT (%d removed, %d added) - the wave changed "
              "shape since it was recorded" % (sum(stale_lost.values()), sum(stale_new.values())))
        for line, n in sorted(stale_lost.items()):
            print("  WAS LOST  x%d  %s" % (n, line[:110]))
        for line, n in sorted(stale_new.items()):
            print("  WAS NEW   x%d  %s" % (n, line[:110]))
        return 1

    if approved_lost or approved_new:
        print("declared edits matched : %d removed, %d added (reviewed in %s)"
              % (sum(approved_lost.values()), sum(approved_new.values()),
                 os.path.basename(APPROVALS)))

    print("\nOK: no original line was lost, duplicated or changed beyond the edits on record.")
    return structural_check()


if __name__ == "__main__":
    sys.exit(main())
